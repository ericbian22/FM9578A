const assert=require('node:assert/strict');
const {binomial,payoff,brownian}=require('../assets/models.js');
const near=(a,b,tol=1e-9)=>assert.ok(Math.abs(a-b)<tol,a+' differs from '+b);
const p={S:45,K:48,r:.05,q:0,sigma:.3,T:1,N:2,kind:'put'};
const eu=binomial(p),am=binomial({...p,style:'american'});
assert.ok(am.price>=eu.price);assert.ok(am.levels[1].exercise[0]>am.levels[1].continuation[0]);
const base={S:100,K:100,r:.05,q:0,sigma:.2,T:1,N:50};
near(binomial(base).price,binomial({...base,style:'american'}).price);
near(binomial(base).price-binomial({...base,kind:'put'}).price,100-100*Math.exp(-.05),1e-8);
const fx=binomial({...base,q:.03,underlying:'fx'});near(fx.p*fx.u+(1-fx.p)*fx.d,Math.exp(.02/50));
const fut=binomial({...base,underlying:'future'});near(fut.p*fut.u+(1-fut.p)*fut.d,1);
assert.throws(()=>binomial({...base,r:5,N:1}));assert.throws(()=>binomial({...base,N:1.5}));
near(payoff(75,75,20,'straddle'),0);near(payoff(60,75,20,'straddle'),15);
near(payoff(100,90,10,'butterfly'),10);near(payoff(120,90,10,'butterfly'),0);
near(payoff(130,90,10,'bull'),10);near(payoff(0,90,10,'bear'),10);
for(const row of brownian(2,1,9578))near(row[1],row[2]);
for(const row of brownian(2,-1,9578))near(row[1],-row[2]);
assert.deepEqual(brownian(1,.4,1),brownian(1,.4,1));assert.throws(()=>brownian(1,1.1,1));
console.log('PASS: parity, American dominance, FX/futures growth, payoffs, validation, Brownian construction.');
